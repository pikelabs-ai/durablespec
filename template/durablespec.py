#!/usr/bin/env python3
"""DurableSpec mechanical tool: build doc/spec/INDEX.md and check the spec for drift.

Lives at doc/spec/durablespec.py and is identical in every repo; no settings. Python 3.8+, stdlib only.

    python3 doc/spec/durablespec.py index     # rewrite INDEX.md from each document's front matter
    python3 doc/spec/durablespec.py check     # exit 1 if anything below is wrong
    python3 doc/spec/durablespec.py version
    python3 doc/spec/durablespec.py upgrade   # install the newest release here [--dry-run]

check verifies: every document has front matter with a purpose and no unknown keys; every owns: path is
inside the repo and still exists; relative links between documents resolve; no two decision records
share a number; INDEX.md is current. It also notes, without failing, design documents that name no code
(fine for work not built yet) and top-level folders that no owns: line covers.

upgrade finds the newest release tag (vX.Y.Z) with git, fetches it into a temporary folder, and runs its
installer against this repo. Set DURABLESPEC_SOURCE to use a mirror instead of GitHub.

Front matter is a small subset of YAML: one line per value; lists either inline [a, b] or as "- item"
lines; values containing commas belong in the "- item" form.
"""
import glob
import os
import re
import subprocess
import sys
import tempfile

VERSION = "0.3.4"

SPEC = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(SPEC))
INDEX = os.path.join(SPEC, "INDEX.md")
RELATED = os.path.join(SPEC, "RELATED.md")
SKIP = {"INDEX.md", "RELATED.md"}
GROUPS = [("(root)", "Start here"), ("purpose", "Purpose"), ("constitution", "Constitution"),
          ("design", "Design"), ("adr", "Decision records")]
KEYS = {"purpose", "concepts", "owns"}
FIRST = ["README.md", "overview.md", "architecture.md"]  # listed first in their group
NO_OWNS = {"design/architecture.md", "design/status.md"}


def _list(value):
    value = value.strip()
    if value.startswith("[") and value.endswith("]"):
        return [v.strip().strip("'\"") for v in value[1:-1].split(",") if v.strip()]
    return [value.strip("'\"")] if value else []


def parse(path):
    """Return dict(title, purpose, concepts, owns, has_front_matter) for one markdown file."""
    with open(path, encoding="utf-8-sig") as fh:  # tolerates a byte-order mark
        text = fh.read().replace("\r\n", "\n")
    doc = {"title": "", "purpose": "", "concepts": [], "owns": [], "has_front_matter": False,
           "unknown": []}
    body = text
    if text.startswith("---\n") and "\n---" in text[4:]:
        end = text.index("\n---", 4)
        front, body = text[4:end], text[end + 4:]
        doc["has_front_matter"] = True
        key = None
        for line in front.split("\n"):
            item = re.match(r"^\s+-\s+(.*)$", line)
            if item and key in ("concepts", "owns"):
                doc[key].append(item.group(1).strip().strip("'\""))
                continue
            m = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
            if not m:
                continue
            key, value = m.group(1), m.group(2)
            if key not in KEYS:
                doc["unknown"].append(key)
            if key == "purpose":
                doc["purpose"] = value.strip().strip("'\"")
            elif key in ("concepts", "owns"):
                doc[key] = _list(value)
    m = re.search(r"^#\s+(.+)$", body, re.MULTILINE)
    doc["title"] = m.group(1).strip() if m else os.path.basename(path)
    return doc


def documents():
    docs = []
    for root, dirs, files in os.walk(SPEC):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for name in sorted(files):
            if name.endswith(".md") and name not in SKIP:
                full = os.path.join(root, name)
                docs.append((os.path.relpath(full, SPEC).replace(os.sep, "/"), parse(full)))
    return docs


def render(docs):
    out = ["<!-- Generated by doc/spec/durablespec.py. Do not edit by hand: change a document's",
           "     front matter (purpose, concepts, owns) and run: python3 doc/spec/durablespec.py index -->",
           "# Spec index", "",
           "Read this first. One line per document: what it is for, the ideas it covers, and the code it "
           "governs. Open the documents that answer your question; don't re-derive what they settle.", ""]
    groups = {}
    for rel, doc in docs:
        top = rel.split("/", 1)[0] if "/" in rel else "(root)"
        groups.setdefault(top, []).append((rel, doc))
    known = [k for k, _ in GROUPS]
    order = GROUPS + [(k, k) for k in sorted(groups) if k not in known]
    def rank(entry):
        name = entry[0].rsplit("/", 1)[-1]
        return (FIRST.index(name) if name in FIRST else len(FIRST), entry[0])

    for key, label in order:
        entries = sorted(groups.get(key, []), key=rank)
        if not entries:
            continue
        out += ["## " + label, ""]
        for rel, doc in entries:
            line = "- [{}]({}) — {}".format(doc["title"], rel, doc["purpose"] or "—")
            if doc["concepts"]:
                line += " · _concepts:_ " + ", ".join(doc["concepts"])
            if doc["owns"]:
                line += " · _owns:_ " + ", ".join(doc["owns"])
            out.append(line)
        out.append("")
    if os.path.exists(RELATED):
        with open(RELATED, encoding="utf-8") as fh:
            out += [fh.read().rstrip(), ""]
    return "\n".join(out).rstrip() + "\n"


def outside_repo(pattern):
    full = os.path.normpath(os.path.join(REPO, pattern))
    return os.path.isabs(pattern) or not (full + os.sep).startswith(REPO + os.sep) and full != REPO


def owned_path_exists(pattern):
    full = os.path.join(REPO, pattern)
    if any(ch in pattern for ch in "*?["):
        return bool(glob.glob(full, recursive=True))
    return os.path.exists(full)


LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
NOT_CODE = {"doc", "docs", "node_modules", "target", "build", "dist", "out", "venv"}


def broken_links(rel):
    with open(os.path.join(SPEC, rel), encoding="utf-8-sig") as fh:
        text = re.sub(r"`[^`\n]*`", "", re.sub(r"```.*?```", "", fh.read(), flags=re.S))
    bad = []
    for target in LINK.findall(text):
        if re.match(r"^[a-z]+:", target) or target.startswith("#"):
            continue
        path = target.split("#", 1)[0]
        if path and not os.path.exists(os.path.normpath(os.path.join(SPEC, os.path.dirname(rel), path))):
            bad.append(target)
    return bad


ARCH = "design/architecture.md"


def slug(heading):
    """The anchor GitHub and GitLab give a heading."""
    return re.sub(r"[^\w\- ]", "", heading.strip().lower()).replace(" ", "-")


def diagrams(rel):
    """The anchor of the heading above each Mermaid diagram in one document ('' if none)."""
    with open(os.path.join(SPEC, rel), encoding="utf-8-sig") as fh:
        lines = fh.read().split("\n")
    found, heading, seen, fence = [], "", {}, None
    for line in lines:
        m = re.match(r"^\s*```(\w*)", line)
        if m:
            if fence is None:
                fence = m.group(1) or "text"
                if fence == "mermaid":
                    found.append(heading)
            else:
                fence = None
            continue
        h = re.match(r"^#{1,6}\s+(.+?)\s*$", line) if fence is None else None
        if h:
            base = slug(h.group(1))
            heading = base + ("-{}".format(seen[base]) if base in seen else "")
            seen[base] = seen.get(base, 0) + 1
    return found


def unlisted_diagrams(docs):
    """Diagrams that design/architecture.md, the hub, doesn't link to."""
    with open(os.path.join(SPEC, ARCH), encoding="utf-8-sig") as fh:
        text = re.sub(r"`[^`\n]*`", "", re.sub(r"```.*?```", "", fh.read(), flags=re.S))
    links = set()
    for target in LINK.findall(text):
        if re.match(r"^[a-z]+:", target):
            continue
        path, _, anchor = target.partition("#")
        rel = os.path.normpath(os.path.join("design", path)).replace(os.sep, "/") if path else ARCH
        links.add((rel, anchor))
    missing = []
    for rel, _ in docs:
        if rel == "README.md":  # the rules: its diagram is an example
            continue
        for anchor in diagrams(rel):
            if (rel, anchor) not in links and not (anchor == "" and any(r == rel for r, _ in links)):
                missing.append((rel, anchor))
    return missing


def uncovered_folders(docs):
    owned = [o.rstrip("/").split("/", 1)[0] for _, d in docs for o in d["owns"]]
    try:
        tops = sorted(n for n in os.listdir(REPO) if os.path.isdir(os.path.join(REPO, n))
                      and not n.startswith(".") and n not in NOT_CODE)
    except OSError:
        return []
    return [t for t in tops if t not in owned]


def check(docs):
    problems, notes = [], []
    for rel, _ in docs:
        for target in broken_links(rel):
            problems.append("{}: link to '{}' does not resolve".format(rel, target))
    if any(rel == ARCH for rel, _ in docs):
        for rel, anchor in unlisted_diagrams(docs):
            problems.append("{}: diagram{} is not listed in {}'s Diagrams section".format(
                rel, " under #" + anchor if anchor else "", ARCH))
    elif any(diagrams(rel) for rel, _ in docs if rel != "README.md"):
        notes.append("the spec has diagrams but no {} to list them".format(ARCH))
    if any(d["owns"] for _, d in docs):
        for folder in uncovered_folders(docs):
            notes.append("top-level folder '{}/' is not covered by any owns: line".format(folder))
    for rel, doc in docs:
        if not doc["has_front_matter"]:
            problems.append("{}: no front matter (needs at least a purpose line)".format(rel))
        elif not doc["purpose"]:
            problems.append("{}: front matter has no purpose".format(rel))
        for key in doc["unknown"]:
            problems.append("{}: unknown front-matter key '{}' (expected purpose, concepts, owns)".format(rel, key))
        if rel.startswith("design/") and rel not in NO_OWNS and doc["has_front_matter"] and not doc["owns"]:
            notes.append("{}: names no code (owns:); fine if it describes work not built yet".format(rel))
        for pattern in doc["owns"]:
            if outside_repo(pattern):
                problems.append("{}: owns '{}', which is outside the repo".format(rel, pattern))
            elif not owned_path_exists(pattern):
                problems.append("{}: owns '{}', which no longer exists".format(rel, pattern))
    numbers = {}
    for rel, _ in docs:
        m = re.match(r"^adr/(\d+)[-_]", rel)
        if m:
            numbers.setdefault(int(m.group(1)), []).append(rel)
    for number, rels in sorted(numbers.items()):
        if len(rels) > 1:
            problems.append("decision record number {} is used by {}".format(number, ", ".join(rels)))
    current = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else None
    if current != render(docs):
        problems.append("INDEX.md is out of date: run python3 doc/spec/durablespec.py index")
    return problems, notes


def _release(text):
    return tuple(int(n) for n in text.split("."))


def upgrade(argv):
    if os.path.exists(os.path.join(REPO, "install.py")) and os.path.isdir(os.path.join(REPO, "skills", "durablespec-update")):
        print("this is the DurableSpec repository itself; pull it instead of upgrading it")
        return 1
    source = os.environ.get("DURABLESPEC_SOURCE", "https://github.com/pikelabs-ai/durablespec.git")
    found = subprocess.run(["git", "ls-remote", "--tags", "--refs", source],
                           stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
    if found.returncode != 0:
        print("could not list releases at {}: {}".format(source, found.stderr.strip()))
        return 1
    tags = re.findall(r"refs/tags/v(\d+\.\d+\.\d+)$", found.stdout, re.M)
    if not tags:
        print("no releases found at " + source)
        return 1
    latest = max(tags, key=_release)
    if _release(latest) <= _release(VERSION):
        print("durablespec {} is installed; the newest release is {}. Nothing to upgrade.".format(VERSION, latest))
        return 0
    print("Upgrading durablespec {} to {} from {}".format(VERSION, latest, source), flush=True)
    with tempfile.TemporaryDirectory() as tmp:
        clone = os.path.join(tmp, "durablespec")
        fetched = subprocess.run(["git", "clone", "-q", "--depth", "1", "--branch", "v" + latest, source, clone],
                                 stderr=subprocess.PIPE, universal_newlines=True)
        if fetched.returncode != 0:
            print("could not fetch v{}: {}".format(latest, fetched.stderr.strip()))
            return 1
        extra = ["--dry-run"] if "--dry-run" in argv else []
        return subprocess.run([sys.executable, os.path.join(clone, "install.py"), REPO] + extra).returncode


def main(argv):
    command = argv[1] if len(argv) > 1 else "check"
    if command == "version":
        print("durablespec", VERSION)
        return 0
    if command == "upgrade":
        return upgrade(argv)
    docs = documents()
    if command == "index":
        with open(INDEX, "w", encoding="utf-8") as fh:
            fh.write(render(docs))
        print("wrote doc/spec/INDEX.md ({} documents)".format(len(docs)))
        return 0
    if command == "check":
        problems, notes = check(docs)
        for p in problems:
            print("  problem: " + p)
        for n in notes:
            print("  note:    " + n)
        print("durablespec {}: {} documents, {}".format(
            VERSION, len(docs), "no problems" if not problems else "{} problem(s)".format(len(problems))))
        return 1 if problems else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
